interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
}

const formatMessage = (template: string, values?: Record<string, string | number>) => {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
};

export const useI18n = create<I18nState>((set) => ({
  locale: initialLocale,
  setLocale: (locale) => {
    writeStoredLocale(locale);
    set({ locale });
  },
  toggleLocale: () => set((state) => {
    const locale = state.locale === 'zh' ? 'en' : 'zh';
    writeStoredLocale(locale);
    return { locale };
  }),
}));

export const useT = () => {
  const locale = useI18n((state) => state.locale);
  const setLocale = useI18n((state) => state.setLocale);
  const toggleLocale = useI18n((state) => state.toggleLocale);
  return {
    locale,
    setLocale,
    toggleLocale,
    t: (key: string, values?: Record<string, string | number>) => {
      const template = messages[locale][key] || messages.zh[key] || key;
      return formatMessage(template, values);
    },
  };
};
